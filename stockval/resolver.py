def resolve(token):
    """把用户输入解析成 6 位代码。支持：纯代码 / 精确名称 / 模糊包含 / 东财搜索兜底。"""
    token = (token or "").strip()
    if not token:
        raise ValueError("请输入股票代码或名称")
    # 1) 纯 6 位代码
    if token.isdigit() and len(token) == 6:
        return token
    # 2) 精确名称
    if token in NAME_MAP:
        return NAME_MAP[token]
    # 3) 模糊包含（名称含输入 或 输入含名称）
    for name, code in NAME_MAP.items():
        if token in name or name in token:
            return code
    # 4) 东财搜索兜底（联网，best-effort）
    code = _em_search(token)
    if code:
        return code
    raise ValueError(
        f"无法解析股票「{token}」。请直接使用 6 位代码，例如：stockval add 600519"
    )


def _em_search(q):
    try:
        url = "https://suggest3.datacenter.eastmoney.com/api/suggest/get"
        params = {
            "input": q, "type": "14", "token": "",
            "maxPage": "1", "pageSize": "10", "app": "quote",
        }
        r = requests.get(url, params=params, headers={"User-Agent": UA}, timeout=8)
        d = r.json()
        tbl = d.get("QuotationCodeTable", {})
        rows = tbl.get("Data", []) if isinstance(tbl, dict) else []
        for row in rows:
            # row[0] 形如 "1.600519" / "0.000001"
            code_full = row[0] if row else ""
            code = str(code_full).split(".")[-1]
            if len(code) == 6 and code.isdigit():
                return code
    except Exception:
        return None
    return None
